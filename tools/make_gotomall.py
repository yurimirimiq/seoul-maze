SRC = UNIT_M * 10  # 칸 너비 1 = poi.tsv 좌표로 얼마(10cm 단위)


def src(x, y):
    return f"{round(x * SRC)},{round(y * SRC)}"


def box(x0, y0, x1, y1):
    return " ".join(src(x, y) for x, y in ((x0, y0), (x1, y0), (x1, y1), (x0, y1)))


def main():
    shapes, pois, seen = [], [], set()
    # 바닥: 가운데 긴 복도와 양 끝 광장(모서리를 깎은 네모). 가게 칸보다 먼저 적어야 밑에 깔린다.
    def octagon(x0, y0, x1, y1, cut=2.0):
        p = [(x0 + cut, y0), (x1 - cut, y0), (x1, y0 + cut), (x1, y1 - cut), (x1 - cut, y1), (x0 + cut, y1), (x0, y1 - cut), (x0, y0 + cut)]
        return " ".join(src(x, y) for x, y in p)
    shapes.append(("B1", "바닥면", "floor-strip", box(-1.0, -3.33, 155.3, 3.33)))
    shapes.append(("B1", "바닥면", "floor-west", octagon(-15.6, -5.4, -0.5, 6.0)))
    shapes.append(("B1", "바닥면", "floor-east", octagon(154.8, -6.9, 174.4, 6.9)))

    def unit(name, x, y0, y1, w):
        assert name not in seen, f"칸이 두 번 나옴: {name}"
        seen.add(name)
        shapes.append(("B1", "가게", name, box(x - w / 2, y0, x + w / 2, y1)))
        pois.append(("B1", "가게", name, *src(x, (y0 + y1) / 2).split(","), name))

    for seg, row, first, last, px0, px1 in RUNS:
        base_px, base_x, pitch = SEG[seg]
        n = last - first
        step = (px1 - px0) / n if n else pitch
        for i in range(n + 1):
            unit(f"{row}{first + i:03d}", (px0 + i * step - base_px) / pitch + base_x, *ROWS[row], w=step / pitch)
    for num, (px, py) in G_PLAZA.items():
        x, y = (px - 682) / 32.1, (py - 617) / 32.1
        unit(f"G{num:03d}", x, y - 0.45, y + 0.45, w=0.9)
    for num, (px, py) in T_PLAZA.items():
        x, y = (px - 105) / 30.2 + 139.3, (py - 932) / 22.2
        unit(f"T{num:03d}", x, y - 0.45, y + 0.45, w=0.9)
    for row, count in {"A": 144, "B": 122, "C": 122, "D": 141, "G": 33, "T": 47}.items():
        missing = [n for n in range(1, count + 1) if f"{row}{n:03d}" not in seen]
        assert not missing, f"{row}줄에서 빠진 번호: {missing}"

    for name, (x, y) in GATES.items():
        pois.append(("B1", "안내", name, *src(x, y).split(","), ""))
    for x, y in TOILETS:
        pois.append(("B1", "편의시설", "화장실", *src(x, y).split(","), ""))

    # 길찾기용 통로 선: A-B줄 사이 북쪽 복도와 C-D줄 사이 남쪽 복도를 한 칸 간격으로 잇고,
    # B·C줄이 끊긴 곳(가로지르는 통로)과 양 끝 광장, 출입구를 가까운 복도에 붙인다.
    north, south, paths = -1.67, 1.67, []
    for x in range(-1, 155):
        paths += [(x, north, x + 1, north), (x, south, x + 1, south)]
    b_runs = sorted(((px0 - SEG[seg][0]) / SEG[seg][2] + SEG[seg][1], (px1 - SEG[seg][0]) / SEG[seg][2] + SEG[seg][1])
                    for seg, row, first, last, px0, px1 in RUNS if row == "B")
    crossings = [-1, 155] + [round((end + nxt) / 2) for (_, end), (nxt, _) in zip(b_runs, b_runs[1:]) if nxt - end > 1.5]
    paths += [(x, north, x, south) for x in sorted(set(crossings))]
    west, east = (-8.0, 0.3), (164.5, 0.0)  # 광장 가운데
    paths += [(*west, -1, north), (*west, -1, south), (*east, 155, north), (*east, 155, south)]
    for name, (x, y) in GATES.items():
        hub = west if x < -1 else east if x > 155 else (min(max(round(x), -1), 155), north if y < 0 else south)
        paths.append((x, y, *hub))

    with open("gosok/paths.tsv", "w", encoding="utf-8") as f:
        f.write("# make_gotomall.py가 만든 파일. 고속터미널 지하상가의 길찾기용 통로 선(토막마다 양 끝점). 좌표계는 poi.tsv와 같다.\n")
        f.write("# 층\tx1\ty1\tx2\ty2\n")
        f.writelines("B1\t" + "\t".join(str(round(v * SRC)) for v in p) + "\n" for p in paths)
    with open("gosok/shapes.tsv", "w", encoding="utf-8") as f:
        f.write("# make_gotomall.py가 만든 파일. 손으로 고치지 말고 make_gotomall.py를 고쳐서 다시 돌린다.\n")
        f.write("# 고속터미널 지하상가(고투몰)의 바닥과 가게 칸. 좌표는 10cm 단위이고 A001 가운데가 원점, 동쪽과 남쪽이 +다.\n")
        f.write("# 층\t종류\tid\t꼭짓점들\n")
        f.writelines("\t".join(s) + "\n" for s in shapes)
    with open("gosok/poi.tsv", "w", encoding="utf-8") as f:
        f.write("# make_gotomall.py가 만든 파일. 손으로 고치지 말고 make_gotomall.py를 고쳐서 다시 돌린다.\n")
        f.write("# 고속터미널 지하상가의 가게 칸 번호, 출입구, 화장실 위치. 가게 이름은 없다(공개된 배치도에 칸 번호만 있다).\n")
        f.write("# 층\t종류\t이름\tx\ty\t자리\n")
        f.writelines("\t".join(p) + "\n" for p in pois)
    print(f"gosok/shapes.tsv, poi.tsv, paths.tsv 저장: 가게 칸 {len(seen)}개, 출입구와 연결통로 {len(GATES)}곳, 화장실 {len(TOILETS)}곳, 통로 토막 {len(paths)}개")


if __name__ == "__main__":
    main()
